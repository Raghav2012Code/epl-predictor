"""Runtime validation for the dashboard dataset contract.

The dataset is an application boundary: it is generated by Python but consumed
by both the API and a TypeScript client.  Validate the fields that the client
renders before serving or accepting the payload so a partial export fails
closed instead of producing a broken dashboard.
"""

from __future__ import annotations

import math
from typing import Any, Mapping


_FIXTURE_FIELDS = (
    "id", "gameweek", "date", "time", "homeTeam", "awayTeam", "homeShort", "awayShort",
    "homeBadge", "awayBadge", "homeColor", "awayColor", "stadium", "predictedScore",
    "predHomeGoals", "predAwayGoals", "homeWinProb", "drawProb", "awayWinProb",
    "predictedOutcome", "status", "actualScore",
)


def _require_mapping(value: Any, path: str) -> Mapping[str, Any]:
    if not isinstance(value, Mapping):
        raise ValueError(f"{path} must be an object.")
    return value


def _require_list(value: Any, path: str) -> list[Any]:
    if not isinstance(value, list):
        raise ValueError(f"{path} must be an array.")
    return value


def _require_string(value: Any, path: str) -> None:
    if not isinstance(value, str) or not value.strip():
        raise ValueError(f"{path} must be a non-empty string.")


def _require_finite_number(value: Any, path: str) -> None:
    if isinstance(value, bool) or not isinstance(value, (int, float)) or not math.isfinite(float(value)):
        raise ValueError(f"{path} must be a finite number.")


def validate_web_dataset(payload: Any) -> dict[str, Any]:
    """Validate and return a dashboard dataset without changing its values."""
    data = _require_mapping(payload, "dataset")
    for field in ("season", "meta"):
        if field not in data:
            raise ValueError(f"dataset.{field} is required.")
    _require_string(data["season"], "dataset.season")
    _require_mapping(data["meta"], "dataset.meta")

    fixtures = _require_list(data.get("fixtures"), "dataset.fixtures")
    if not fixtures:
        raise ValueError("dataset.fixtures must not be empty.")
    fixture_ids: set[int | float] = set()
    for index, fixture in enumerate(fixtures):
        item = _require_mapping(fixture, f"fixtures[{index}]")
        for field in _FIXTURE_FIELDS:
            if field not in item:
                raise ValueError(f"fixtures[{index}].{field} is required.")
        for field in ("date", "time", "homeTeam", "awayTeam", "homeShort", "awayShort", "status"):
            _require_string(item[field], f"fixtures[{index}].{field}")
        for field in ("id", "gameweek", "predHomeGoals", "predAwayGoals"):
            _require_finite_number(item[field], f"fixtures[{index}].{field}")
        fixture_id = item["id"]
        if fixture_id in fixture_ids:
            raise ValueError(f"fixtures[{index}].id values must be unique.")
        fixture_ids.add(fixture_id)
        gameweek = float(item["gameweek"])
        if not gameweek.is_integer() or not 1 <= gameweek <= 38:
            raise ValueError(f"fixtures[{index}].gameweek must be between 1 and 38.")
        for field in ("homeWinProb", "drawProb", "awayWinProb"):
            _require_finite_number(item[field], f"fixtures[{index}].{field}")
            if not 0 <= float(item[field]) <= 100:
                raise ValueError(f"fixtures[{index}].{field} must be between 0 and 100.")
        probability_total = sum(float(item[field]) for field in ("homeWinProb", "drawProb", "awayWinProb"))
        if abs(probability_total - 100.0) > 0.15:
            raise ValueError(f"fixtures[{index}] probabilities must total 100.")

    if "totalMatches" in data:
        _require_finite_number(data["totalMatches"], "dataset.totalMatches")
        total_matches = float(data["totalMatches"])
        if not total_matches.is_integer() or int(total_matches) != len(fixtures):
            raise ValueError("dataset.totalMatches must match the fixture count.")

    benchmark = _require_mapping(data.get("benchmark"), "dataset.benchmark")
    _require_list(benchmark.get("models"), "dataset.benchmark.models")
    analytics = _require_mapping(data.get("analytics"), "dataset.analytics")
    distribution = _require_mapping(analytics.get("outcomeDistribution"), "dataset.analytics.outcomeDistribution")
    for field in ("home", "draw", "away", "homePct", "drawPct", "awayPct"):
        _require_finite_number(distribution.get(field), f"dataset.analytics.outcomeDistribution.{field}")
    _require_list(analytics.get("goalsPerGameweek"), "dataset.analytics.goalsPerGameweek")
    _require_mapping(data.get("teams"), "dataset.teams")
    _require_mapping(data.get("clubSeries"), "dataset.clubSeries")
    return dict(data)
